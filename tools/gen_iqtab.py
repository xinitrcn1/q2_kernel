#!/usr/bin/env python3
"""Generate src/iqtab.c: the i-quant codebooks and sign tables.

The tables are data from ggml's ggml-common.h (MIT License, Copyright
(c) 2023-2024 The ggml authors); only the values are taken.
    python3 tools/gen_iqtab.py path/to/ggml-common.h > src/iqtab.c
"""
import re
import sys

src = open(sys.argv[1]).read()
want = ['kmask_iq2xs', 'ksigns_iq2xs', 'iq2xxs_grid', 'iq2xs_grid', 'iq2s_grid',
        'iq3xxs_grid', 'iq3s_grid', 'kvalues_iq4nl', 'iq1s_grid']
out = sys.stdout
out.write('/* generated by tools/gen_iqtab.py from ggml-common.h; do not edit.\n'
          ' * Table values from ggml (MIT License, (c) 2023-2024 The ggml authors). */\n')
out.write('#include "iqtab.h"\n\n')
for name in want:
    m = re.search(r'GGML_TABLE_BEGIN\((\w+),\s*' + name + r',\s*(\w+)\)(.*?)GGML_TABLE_END\(\)',
                  src, re.S)
    if not m:
        sys.exit('table %s not found' % name)
    ctype, size, body = m.group(1), m.group(2), m.group(3)
    body = re.sub(r'//[^\n]*', '', body)
    vals = [v for v in re.split(r'[\s,]+', body.strip()) if v]
    if size == 'NGRID_IQ1S':
        size = '2048'
    assert len(vals) == int(size), (name, len(vals), size)
    out.write('const %s %s[%s] = {\n' % (ctype, name, size))
    per = 4 if ctype == 'uint64_t' else 8
    for i in range(0, len(vals), per):
        out.write('\t' + ', '.join(vals[i:i + per]) + ',\n')
    out.write('};\n\n')
