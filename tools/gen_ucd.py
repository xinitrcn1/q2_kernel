#!/usr/bin/env python3
"""Generate src/ucd.c: codepoint class ranges for the pre-tokenizer.

Flags: 1 letter (L*), 2 number (N*), 4 whitespace (llama.cpp's set),
8 assigned (any category but Cn), 16 mark (M*).  Run: python3 tools/gen_ucd.py > src/ucd.c
"""
import sys
import unicodedata

WS = {0x9, 0xA, 0xB, 0xC, 0xD, 0x20, 0x85, 0xA0, 0x1680, 0x2028, 0x2029,
      0x202F, 0x205F, 0x3000} | set(range(0x2000, 0x200B))


def flags(cp):
    cat = unicodedata.category(chr(cp))
    f = 0
    if cat[0] == 'L':
        f |= 1
    if cat[0] == 'N':
        f |= 2
    if cp in WS:
        f |= 4
    if cat != 'Cn':
        f |= 8
    if cat[0] == 'M':
        f |= 16
    return f


rows = []
cur, start = flags(0), 0
for cp in range(1, 0x110000):
    f = flags(cp)
    if f != cur:
        rows.append((start, cp - 1, cur))
        cur, start = f, cp
rows.append((start, 0x10FFFF, cur))
rows = [r for r in rows if r[2]]

out = sys.stdout
out.write("/* generated by tools/gen_ucd.py (Unicode %s); do not edit */\n"
          % unicodedata.unidata_version)
out.write('#include "tok.h"\n\n')
out.write("const ucd_range ucd_ranges[] = {\n")
for a, b, f in rows:
    out.write("\t{ 0x%x, 0x%x, %d },\n" % (a, b, f))
out.write("};\n")
out.write("const int ucd_nranges = %d;\n" % len(rows))
